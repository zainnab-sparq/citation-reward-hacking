       caption = paste("E2, extended random-effects sensitivity with maximal",
                       "condition slopes. Singular under both pipelines,",
                       "concentrated in the three-level family factor."))
)

parse_args <- function(args) {
  out <- list(outdir = "paper/tables")
  i <- 1L
  while (i <= length(args)) {
    key <- sub("^--", "", args[i])
    if (!key %in% names(out)) stop(sprintf("Unknown argument: %s", args[i]))
    out[[key]] <- args[i + 1L]
    i <- i + 2L
  }
  out
}

main <- function() {
  args <- parse_args(commandArgs(trailingOnly = TRUE))
  dir.create(args$outdir, recursive = TRUE, showWarnings = FALSE)

  for (spec in TABLES) {
    left <- .read_block(spec$corrected, spec$block)
    right <- .read_block(spec$registered, spec$block)
    rows <- pair_coefficients(left$coefficients, right$coefficients)
    path <- file.path(args$outdir, paste0("coef_", spec$name, ".tex"))
    writeLines(emit_table(rows, spec$caption, spec$label), path)
    singular <- if (is.null(left$is_singular)) "n/a" else as.character(left$is_singular)
    converged <- if (is.null(left$converged)) "n/a" else as.character(left$converged)
    cat(sprintf("  %-14s %2d terms, corrected singular=%s converged=%s -> %s\n",
                spec$name, length(rows), singular, converged, path))
  }
  invisible(NULL)
}

if (sys.nframe() == 0L) main()
