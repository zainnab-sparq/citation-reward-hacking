# Emit the appendix B coefficient tables as LaTeX fragments.
#
# Eight fitted models contribute roughly 176 coefficient rows. Transcribing
# those by hand would be a guaranteed source of quiet errors, so the .tex
# fragments under paper/tables/ are generated from the result artifacts and are
# never edited by hand.
#
# The corrected and registered pipelines are paired ON TERM NAME. Pairing by
# position would put one pipeline's number against the other's term if the two
# artifacts ever ordered their coefficients differently, and every value would
# still look plausible. The pairing refuses to emit when the term sets differ.
#
# Usage (from repo root):
#   Rscript src/analysis/coefficient_tables.R --outdir paper/tables

suppressPackageStartupMessages({ library(jsonlite) })

ARTIFACT_DIR <- "data/analysis/phase_c"
# Below this, a p-value is printed in scientific form rather than as 0.000.
P_PRINT_FLOOR <- 1e-3
# Doubles lose all precision below roughly 1e-308, so any p at or under this is
# reported as a bound rather than as a value the arithmetic cannot support.
UNDERFLOW_P <- 1e-300
UNDERFLOW_EXPONENT <- -300L

.esc_term <- function(term) {
  paste0("\\texttt{", gsub("_", "\\\\_", term), "}")
}

#' Holm-adjusted p where the analysis computed one, raw p otherwise. Only the
#' pre-registered confirmatory families carry a Holm adjustment, so most rows
#' fall back to the raw value and the table caption says which are which.
.coef_p <- function(coefficient) {
  if (!is.null(coefficient$p_holm)) return(coefficient$p_holm)
  coefficient$p_value
}

.fmt_p <- function(p) {
  if (is.null(p) || (length(p) == 1L && is.na(p))) return("---")
  if (p >= P_PRINT_FLOOR) return(sprintf("%.3f", p))
  # E2's interaction is far enough out that R's p underflows to exactly 0.
  # Printing that as 0.000 would read as a rounded value rather than as a
  # quantity below the smallest double, so it becomes an explicit bound.
  if (p <= UNDERFLOW_P) return(sprintf("$<10^{%d}$", UNDERFLOW_EXPONENT))
  exponent <- as.integer(floor(log10(p)))
  mantissa <- p / 10^exponent
  sprintf("$%.1f \\times 10^{%d}$", mantissa, exponent)
}

.fmt_est <- function(coefficient) {
  if (is.null(coefficient)) return("---")
  sprintf("%.2f (%.3f)", coefficient$estimate, coefficient$std_error)
}

#' Join two coefficient lists on term, preserving the left list's order.
pair_coefficients <- function(left, right) {
  left_terms <- vapply(left, function(c) c$term, character(1))
  right_terms <- vapply(right, function(c) c$term, character(1))
  if (!setequal(left_terms, right_terms)) {
    missing <- c(setdiff(left_terms, right_terms), setdiff(right_terms, left_terms))
    stop(sprintf("coefficient term sets differ; refusing to pair by position (%s)",
                 paste(missing, collapse = ", ")))
  }
  names(right) <- right_terms
  lapply(seq_along(left), function(i) {
    list(term = left_terms[i], left = left[[i]], right = right[[left_terms[i]]])
  })
}

emit_table_body <- function(rows) {
  lines <- vapply(rows, function(r) {
    sprintf("%s & %s & %s & %s & %s \\\\",
            .esc_term(r$term),
            .fmt_est(r$left), .fmt_p(.coef_p(r$left)),
            .fmt_est(r$right), .fmt_p(.coef_p(r$right)))
  }, character(1))
  paste(lines, collapse = "\n")
}

.read_block <- function(file, block) {
  path <- file.path(ARTIFACT_DIR, file)
  j <- fromJSON(path, simplifyVector = FALSE)
  if (is.null(j[[block]])) stop(sprintf("no block '%s' in %s", block, path))
  j[[block]]
}

#' A complete table environment, not a bare row fragment.
#'
#' LaTeX's braced \\input{} appends a \\relax token after the file. Inputting a
#' fragment of rows INSIDE a tabular therefore opens a fresh alignment row after
#' the fragment's final row break, and the \\bottomrule that follows is then a
#' misplaced \\noalign. Emitting the whole environment and inputting it at top
#' level removes the possibility entirely.
emit_table <- function(rows, caption, label) {
  c("% Generated by src/analysis/coefficient_tables.R. Do not edit.",
    "\\begin{table}[htbp]",
    "\\centering",
    sprintf("\\caption{%s}", caption),
    sprintf("\\label{%s}", label),
    "\\scriptsize",
    # Five columns of default padding cost 60pt, which is what pushes the
    # widest E2 term names past the text block. Scoped to this float.
    "\\setlength{\\tabcolsep}{2.5pt}",
    # The longest E1 three-way term still overruns an A4 text block; shrink
    # only when the table is wider than the line.
    "\\begin{adjustbox}{max width=\\linewidth}",
    "\\begin{tabular}{lrrrr}",
    "\\toprule",
    "& \\multicolumn{2}{c}{Corrected} & \\multicolumn{2}{c}{Registered} \\\\",
    "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}",
    "Term & $\\hat\\beta$ (SE) & $p$ & $\\hat\\beta$ (SE) & $p$ \\\\",
    "\\midrule",
    emit_table_body(rows),
    "\\bottomrule",
    "\\end{tabular}",
    "\\end{adjustbox}",
    "\\end{table}")
}

TABLES <- list(
  list(name = "e1_primary", corrected = "e1_corrected_nobootstrap.json",
       registered = "e1_registered_nobootstrap.json", block = "primary",
       label = "tab:coefe1",
       caption = paste("E1, registered parsimony-primary model, corrected and",
                       "registered pipelines side by side. Estimates are on the",
                       "log-odds scale with standard errors in parentheses.",
                       "Holm-adjusted $p$ for the pre-registered confirmatory",
                       "family, raw $p$ elsewhere.")),
  list(name = "e1_extended", corrected = "e1_corrected_nobootstrap.json",
       registered = "e1_registered_nobootstrap.json", block = "sensitivity_extended_re",
       label = "tab:coefe1x",
       caption = paste("E1, extended random-effects sensitivity. Singular under",
                       "both pipelines; the rePCA above locates the deficiency",
                       "in the three-level family factor.")),
  list(name = "e2_primary", corrected = "e2_corrected_nobootstrap.json",
       registered = "e2_registered_nobootstrap.json", block = "primary_open_weights",
       label = "tab:coefe2",
       caption = paste("E2, registered parsimony-primary model on the",
                       "open-weights subsample, which is the whole frame.")),
  list(name = "e2_extended", corrected = "e2_corrected_nobootstrap.json",
